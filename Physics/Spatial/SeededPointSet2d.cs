using System.Collections.ObjectModel;
using TheSingularityWorkshop.Physics.Numerics;

namespace TheSingularityWorkshop.Physics.Spatial;

/// <summary>Generates a bounded, deterministic set of 2D points from a seed.</summary>
/// <remarks>
/// Each point coordinate is sampled by random access from its point index and an axis-specific domain.
/// Results do not depend on mutable random-stream call order. The output is unit-agnostic, may contain
/// duplicate points, and is procedural data rather than a physical distribution or a collision-free packing.
/// </remarks>
public static class SeededPointSet2d
{
    /// <summary>Maximum number of points generated by one call.</summary>
    public const int MaximumPointCount = 65_536;

    private const uint XDomain = 0xA24BAED5u;
    private const uint YDomain = 0x9FB21C65u;
    private const double UInt32Scale = 1.0 / 4_294_967_296.0;

    /// <summary>
    /// Generates points in the half-open rectangle [minX, maxX) × [minY, maxY).
    /// </summary>
    /// <param name="count">Requested number of points, from zero through <see cref="MaximumPointCount"/>.</param>
    /// <param name="minX">Inclusive lower bound for the first coordinate.</param>
    /// <param name="minY">Inclusive lower bound for the second coordinate.</param>
    /// <param name="maxX">Exclusive upper bound for the first coordinate.</param>
    /// <param name="maxY">Exclusive upper bound for the second coordinate.</param>
    /// <param name="seed">Stable 32-bit seed.</param>
    /// <returns>An immutable view of the generated points in stable index order.</returns>
    /// <exception cref="ArgumentOutOfRangeException">
    /// A count or bound is invalid, a bound is non-finite, or either range has a non-finite difference.
    /// </exception>
    public static IReadOnlyList<Vector2d> Generate(
        int count,
        double minX,
        double minY,
        double maxX,
        double maxY,
        uint seed)
    {
        if (count < 0 || count > MaximumPointCount)
        {
            throw new ArgumentOutOfRangeException(nameof(count),
                $"Count must be between zero and {MaximumPointCount}.");
        }

        ValidateRange(minX, maxX, nameof(minX), nameof(maxX));
        ValidateRange(minY, maxY, nameof(minY), nameof(maxY));

        var points = new Vector2d[count];
        for (var i = 0; i < points.Length; i++)
        {
            var index = (uint)i;
            var xSample = Squirrel3.Hash(index, seed ^ XDomain) * UInt32Scale;
            var ySample = Squirrel3.Hash(index, seed ^ YDomain) * UInt32Scale;
            points[i] = new Vector2d(
                MapToHalfOpenRange(minX, maxX, xSample),
                MapToHalfOpenRange(minY, maxY, ySample));
        }

        return new ReadOnlyCollection<Vector2d>(points);
    }

    private static void ValidateRange(double minimum, double maximum, string minimumName, string maximumName)
    {
        if (!double.IsFinite(minimum))
            throw new ArgumentOutOfRangeException(minimumName, "Bound must be finite.");
        if (!double.IsFinite(maximum) || maximum <= minimum)
            throw new ArgumentOutOfRangeException(maximumName, "Exclusive upper bound must be finite and greater than the lower bound.");
        if (!double.IsFinite(maximum - minimum))
            throw new ArgumentOutOfRangeException(maximumName, "Range difference must be finite.");
    }

    private static double MapToHalfOpenRange(double minimum, double maximum, double sample)
    {
        var value = minimum + ((maximum - minimum) * sample);

        // Rounding can produce the exclusive endpoint even though sample is less than one.
        if (value >= maximum)
            return Math.BitDecrement(maximum);

        return value < minimum ? minimum : value;
    }
}
