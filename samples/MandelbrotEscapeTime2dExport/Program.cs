using System.Globalization;
using System.Text.Json;
using TheSingularityWorkshop.Physics.Spatial;

if (args.Length is not (1 or 8))
{
    Console.Error.WriteLine("Usage: MandelbrotEscapeTime2dExport <output.json> [width height maxIterations minReal minImaginary maxReal maxImaginary]");
    Console.Error.WriteLine("Defaults: 160 100 80 -2.5 -1.25 1 1.25");
    return 2;
}

if (!int.TryParse(args.Length == 8 ? args[1] : "160", NumberStyles.None, CultureInfo.InvariantCulture, out var width) ||
    !int.TryParse(args.Length == 8 ? args[2] : "100", NumberStyles.None, CultureInfo.InvariantCulture, out var height) ||
    !int.TryParse(args.Length == 8 ? args[3] : "80", NumberStyles.None, CultureInfo.InvariantCulture, out var maxIterations) ||
    !double.TryParse(args.Length == 8 ? args[4] : "-2.5", NumberStyles.Float, CultureInfo.InvariantCulture, out var minReal) ||
    !double.TryParse(args.Length == 8 ? args[5] : "-1.25", NumberStyles.Float, CultureInfo.InvariantCulture, out var minImaginary) ||
    !double.TryParse(args.Length == 8 ? args[6] : "1", NumberStyles.Float, CultureInfo.InvariantCulture, out var maxReal) ||
    !double.TryParse(args.Length == 8 ? args[7] : "1.25", NumberStyles.Float, CultureInfo.InvariantCulture, out var maxImaginary))
{
    Console.Error.WriteLine("Parameters must be integers for grid/iterations and invariant-culture numbers for bounds.");
    return 2;
}

if (width < 1 || height < 1 || (long)width * height > 262_144 ||
    maxIterations < 1 || maxIterations > 4_096 ||
    (long)width * height * maxIterations > 50_000_000 ||
    !double.IsFinite(minReal) || !double.IsFinite(minImaginary) ||
    !double.IsFinite(maxReal) || !double.IsFinite(maxImaginary) ||
    maxReal <= minReal || maxImaginary <= minImaginary ||
    !double.IsFinite(maxReal - minReal) || !double.IsFinite(maxImaginary - minImaginary))
{
    Console.Error.WriteLine("Parameters exceed supported sample/work limits or define invalid complex-plane bounds.");
    return 2;
}

var samples = MandelbrotEscapeTime2d.Generate(
    width, height, minReal, minImaginary, maxReal, maxImaginary, maxIterations);
var runRecord = new
{
    modelId = "mathematics.mandelbrot-escape-time-2d",
    modelVersion = "1",
    schemaVersion = 1,
    width,
    height,
    maxIterations,
    bounds = new { minReal, minImaginary, maxReal, maxImaginary, convention = "minimum-inclusive, maximum-exclusive; cell centers sampled" },
    sampleCount = samples.Count,
    samples = samples.Select(sample => new
    {
        column = sample.Column,
        row = sample.Row,
        real = sample.Real,
        imaginary = sample.Imaginary,
        iterations = sample.Iterations,
        escaped = sample.Escaped
    }).ToArray()
};

var outputPath = Path.GetFullPath(args[0]);
Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
await File.WriteAllTextAsync(outputPath,
    JsonSerializer.Serialize(runRecord, new JsonSerializerOptions { WriteIndented = true }));

using var parsed = JsonDocument.Parse(await File.ReadAllTextAsync(outputPath));
var root = parsed.RootElement;
var written = root.GetProperty("samples").EnumerateArray().ToArray();
if (root.GetProperty("sampleCount").GetInt32() != samples.Count || written.Length != samples.Count)
    throw new InvalidOperationException("Serialized sample count differs from Physics output.");

for (var i = 0; i < samples.Count; i++)
{
    var sample = samples[i];
    var item = written[i];
    if (item.GetProperty("column").GetInt32() != sample.Column ||
        item.GetProperty("row").GetInt32() != sample.Row ||
        item.GetProperty("real").GetDouble() != sample.Real ||
        item.GetProperty("imaginary").GetDouble() != sample.Imaginary ||
        item.GetProperty("iterations").GetInt32() != sample.Iterations ||
        item.GetProperty("escaped").GetBoolean() != sample.Escaped)
        throw new InvalidOperationException($"Serialized sample {i} differs from Physics output.");
}

Console.WriteLine($"PASS: serialized and re-read {samples.Count} Mandelbrot samples generated by Physics.");
Console.WriteLine($"Model: mathematics.mandelbrot-escape-time-2d v1; grid {width}×{height}; cap {maxIterations}.");
Console.WriteLine($"Window: real [{minReal:R}, {maxReal:R}); imaginary [{minImaginary:R}, {maxImaginary:R}).");
Console.WriteLine($"Escaped samples: {samples.Count(sample => sample.Escaped)}; non-escaped at cap: {samples.Count(sample => !sample.Escaped)}.");
Console.WriteLine($"Generated: {outputPath}");
return 0;
